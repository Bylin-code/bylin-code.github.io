import { chromium } from 'playwright';
import { serve } from './serve-build.mjs';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const { server, url } = await serve(resolve(process.argv[2] || '_site'));
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => route.request().url().startsWith(url) ? route.continue() : route.abort());
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.goto(`${url}/projects/`);
    const cards = page.locator('[data-project-type]:visible');
    assert.equal(await cards.count(), 17);
    await page.getByRole('button', { name: 'Internship work', exact: true }).click();
    assert.equal(await cards.count(), 4);
    await page.getByRole('button', { name: 'Mechanical design', exact: true }).click();
    assert.equal(await cards.count(), 3);
    await page.getByRole('button', { name: 'Creative', exact: true }).click();
    assert.equal(await cards.count(), 0);
    await page.locator('[data-filter-empty]').waitFor({ state: 'visible' });
    await page.getByRole('button', { name: 'Reset filters' }).click();
    assert.equal(await cards.count(), 17);
    assert.equal(await page.locator('.project-grid-item .project-contributions').count(), 0);
    await page.getByRole('button', { name: 'Personal projects', exact: true }).focus();
    await page.keyboard.press('Enter');
    assert.equal(await cards.count(), 13);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `/tmp/brady-projects-${width}.png`, fullPage: false });
    await page.goto(url);
    const hrefs = await page.locator('#selected-work a').evaluateAll(els => [...new Set(els.map(e => e.getAttribute('href')))]);
    assert.deepEqual(hrefs.slice(0, 3), ['/projects/actuator-test-bench/', '/projects/teleoperation-controls/', '/projects/pulse/']);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `/tmp/brady-home-${width}.png`, fullPage: false });
    await page.goto(`${url}/projects/pulse/`);
    assert.match(await page.locator('.project-contributions').innerText(), /Electronics design.*Software development.*Creative.*Leadership/);
    assert.match(await page.locator('iframe').getAttribute('src'), /hYe45-qbswQ/);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `/tmp/brady-pulse-${width}.png`, fullPage: false });
  }
  await page.goto(`${url}/admin/`);
  await page.waitForFunction(() => document.querySelector('#project-preview').contentDocument?.querySelector('.gallery-item'));
  const boxes = page.locator('input[name="contributions"]');
  assert.equal(await boxes.count(), 5);
  await boxes.first().check();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-project').click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  let markdown = '';
  for await (const chunk of stream) markdown += chunk.toString();
  assert.match(markdown, /contributions: \[.*Mechanical design/);
  const noJS = await browser.newPage({ javaScriptEnabled: false });
  await noJS.goto(`${url}/projects/`);
  assert.equal(await noJS.locator('.project-grid-item:visible').count(), 17);
  assert.equal(await noJS.locator('.project-filters:visible').count(), 0);
  assert.equal((await page.request.get(`${url}/assets/images/my-projects/actuator-test-bench/results-dashboard.png`)).status(), 200);
  assert.deepEqual(errors, []);
  console.log('Desktop/mobile filters, empty state, reset, keyboard, no-JS fallback, homepage order, demo, editor export, and dashboard-image availability passed.');
} finally { await browser.close(); server.close(); }
